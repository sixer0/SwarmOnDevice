type Mode = "on" | "consent"
const ROLES = [undefined, "build", "coder", "verifier", "planner"] as const

function editInput(file: string, mode: Mode, agent?: string, editClass?: string): TableModule.AutonomyTable.Input {
  return {
    permission: "edit",
    patterns: [path.relative(dir, file)],
    metadata: { filepath: file },
    instance,
    cwd: dir,
    canUndo: true,
    folder: "clean",
    // What the edit tools said at BASE for a file outside the project: nothing can undo it.
    editClass: (editClass ?? "no_undo") as TableModule.AutonomyTable.Input["editClass"],
    ...(agent !== undefined && { agent }),
    ...(mode === "consent" && {
      bypass: { caller: agent === undefined || agent === "build" ? "root" : "subagent" },
      consent: { id: "c1", files: new Map([[file, "item-1"]]) },
    }),
  } as TableModule.AutonomyTable.Input
}

async function shellInput(command: string, mode: Mode, consented: string[] = []): Promise<TableModule.AutonomyTable.Input> {
  return {
    permission: "bash",
    patterns: [command],
    metadata: { command, workdir: dir, steps: await readSteps(command, dir) },
    instance,
    cwd: dir,
    canUndo: true,
    folder: "clean",
    ...(mode === "consent" && {
      bypass: { caller: "root" as const },
      consent: { id: "c1", files: new Map(consented.map((file) => [file, "item-1"])) },
    }),
  } as TableModule.AutonomyTable.Input
}

const verdictOf = (input: TableModule.AutonomyTable.Input) =>
  input.bypass ? AutonomyTable.classify(input) : AutonomyTable.classifyBase(input)

const trust = (files: string[], canUndo = true) =>
  Effect.runPromiseExit(Reach.editTrust({ trust: { canUndo } }, instance, files) as Effect.Effect<unknown>)
const failure = (exit: Exit.Exit<unknown, unknown>) => {
  if (!Exit.isFailure(exit)) return "succeeded"
  const error = Cause.squash(exit.cause)
  return error instanceof Error ? error.message : String(error)
}

describe("SEC11 N8-442: the refusal text and the vault_mirror literal", () => {
  test("VAULT_MIRROR_REFUSED_TEXT is the N8-442 text", () => {
    expect((Texts as Record<string, unknown>).VAULT_MIRROR_REFUSED_TEXT).toBe(N8_442)
  })

  test("vault_mirror is a DeferredCategory and EditClass literal and an X with its own text, with and without consent", async () => {
    const { PermissionV1 } = await import("@opencode-ai/core/v1/permission")
    expect(PermissionV1.DeferredCategory.literals as readonly string[]).toContain("vault_mirror")
    expect(PermissionV1.EditClass.literals as readonly string[]).toContain("vault_mirror")
    for (const error of [Permission.refusedByMode("vault_mirror"), Permission.refusedUnderConsent("vault_mirror")]) {
      expect((error as Error).message).toContain(N8_442)
      expect((error as Error).message.startsWith("This call did not run.")).toBe(true)
    }
  })
})

describe("SEC11 Reach.editTrust: a mirror file is refused before any prompt; the rest of the vault is not", () => {
  test("<vault>/swarm-memory/x/notes/a.md, with and without Undo", async () => {
    for (const canUndo of [true, false]) expect(failure(await trust([note], canUndo))).toBe(N8_442)
  })

  test("a new file, a new subfolder and the mirror folder itself", async () => {
    for (const file of ["x/notes/new.md", "y/index.md", ""]) expect(failure(await trust([path.join(mirror, file)]))).toBe(N8_442)
  })

  test("the real-path spelling of the vault (e.g. /private/var on macOS)", async () => {
    expect(failure(await trust([path.join(realpathSync(vault), "swarm-memory/x/notes/a.md")]))).toBe(N8_442)
  })

  test.skipIf(process.platform !== "darwin")("another letter case of the mirror folder (macOS ignores case)", async () => {
    expect(failure(await trust([path.join(vault, "Swarm-Memory/x/notes/a.md")]))).toBe(N8_442)
  })

  test("inbox/, the person's own notes and a sibling swarm-memory-old/ are not refused as vault_mirror", async () => {
    for (const file of ["inbox/n.md", "notes/own.md", "swarm-memory-old/x.md"])
      expect(failure(await trust([path.join(vault, file)]))).not.toBe(N8_442)
  })

  test("a project file is unaffected", async () => {
    expect(Exit.isSuccess(await trust([path.join(dir, "a.md")]))).toBe(true)
  })

  test("a symlink in the project that points into the mirror is judged where it lands", async () => {
    const link = path.join(dir, "mlink")
    if (!existsSync(link)) symlinkSync(mirror, link)
    expect(failure(await trust([path.join(link, "x/notes/a.md")]))).toBe(N8_442)
    rmSync(link)
  })
})

describe("SEC11 a symlinked vault root is resolved first", () => {
  let link: string
  beforeAll(() => {
    link = path.join(home, "vault-link")
    symlinkSync(vault, link)
    process.env.SWARM_VAULT_DIR = link
  })
  afterAll(() => {
    process.env.SWARM_VAULT_DIR = vault
    rmSync(link, { force: true })
  })

  test("by the link's name and by the real name: edit tool trust and the table", async () => {
    for (const file of [path.join(link, "swarm-memory/x/notes/a.md"), path.join(realpathSync(vault), "swarm-memory/x/notes/a.md")]) {
      expect(failure(await trust([file]))).toBe(N8_442)
      const verdict = verdictOf(editInput(file, "consent"))
      expect([verdict.class, verdict.category]).toEqual(["X", "vault_mirror"])
    }
    const command = `echo synthetic > ${path.join(realpathSync(vault), "swarm-memory/x/notes/b.md")}`
    const verdict = verdictOf(await shellInput(command, "on"))
    expect([verdict.class, verdict.category]).toEqual(["X", "vault_mirror"])
  })
})

describe("SEC11 the default root ~/.swarm/vault (no SWARM_VAULT_DIR): vault_mirror, not the .swarm state rule", () => {
  let defaultMirror: string
  beforeAll(() => {
    seedVault(path.join(home, ".swarm/vault"))
    defaultMirror = path.join(home, ".swarm/vault/swarm-memory")
    delete process.env.SWARM_VAULT_DIR
  })
  afterAll(() => {
    process.env.SWARM_VAULT_DIR = vault
  })

  for (const mode of ["on", "consent"] as const) {
    test(`mode ${mode}: an edit and a shell write with ~`, async () => {
      const file = path.join(defaultMirror, "x/notes/a.md")
      const edit = verdictOf(editInput(file, mode))
      expect([edit.class, edit.category]).toEqual(["X", "vault_mirror"])
      const shell = verdictOf(await shellInput("echo synthetic >> ~/.swarm/vault/swarm-memory/x/notes/a.md", mode, [file]))
      expect([shell.class, shell.category]).toEqual(["X", "vault_mirror"])
    })
  }

  test("a shell write into ~/.swarm/vault/inbox is not vault_mirror", async () => {
    const verdict = verdictOf(await shellInput("echo synthetic > ~/.swarm/vault/inbox/n.md", "on"))
    expect(verdict.category).not.toBe("vault_mirror")
  })
})

describe("SEC11 the autonomy table: an edit into the mirror is X vault_mirror in every mode and role", () => {
  for (const mode of ["on", "consent"] as const)
    for (const agent of ROLES)
      test(`mode ${mode}, ${agent ?? "no agent"}: swarm-memory/x/notes/a.md`, () => {
        const verdict = verdictOf(editInput(note, mode, agent))
        expect([verdict.class, verdict.category]).toEqual(["X", "vault_mirror"])
      })

  test("an editClass vault_mirror from the edit tools is refused, consent item or not", () => {
    for (const mode of ["on", "consent"] as const) {
      const verdict = verdictOf(editInput(note, mode, undefined, "vault_mirror"))
      expect([verdict.class, verdict.category]).toEqual(["X", "vault_mirror"])
    }
  })

  test("an outside-folder ask that an edit follows is refused as vault_mirror", () => {
    for (const mode of ["on", "consent"] as const) {
      const input = { ...editInput(note, mode), permission: "external_directory", follows: [{ permission: "edit" }] }
      const verdict = verdictOf(input as TableModule.AutonomyTable.Input)
      expect([verdict.class, verdict.category]).toEqual(["X", "vault_mirror"])
    }
  })

  test("an edit into <vault>/inbox keeps its verdict (not vault_mirror)", () => {
    for (const mode of ["on", "consent"] as const)
      expect(verdictOf(editInput(path.join(vault, "inbox/n.md"), mode)).category).not.toBe("vault_mirror")
  })
})

describe("SEC11 the autonomy table: a shell write into the mirror is X vault_mirror, even with a consent item", () => {
  const writes = () => [
    `cat > ${mirror}/x/notes/a.md <<'EOF'\nsynthetic\nEOF`,
    `echo synthetic > ${mirror}/x/notes/b.md`,
    `echo synthetic | tee ${mirror}/x/notes/a.md`,
    `cp a.md ${mirror}/x/notes/`,
    `cp a.md ${mirror}/x/notes/a.md`,
    `mv a.md ${mirror}/x/notes/a.md`,
    `mv ${mirror}/x/notes/a.md moved.md`,
    `rm ${mirror}/x/notes/a.md`,
    `sed -i '' 's/a/b/' ${mirror}/x/notes/a.md`,
    `cd ${mirror} && cp ${dir}/a.md x/notes/b.md`,
    `pushd ${mirror}/x/notes && tee a.md < /dev/null`,
    `cd ${vault} && echo synthetic > swarm-memory/x/notes/c.md`,
  ]
  for (const mode of ["on", "consent"] as const)
    for (const index of writes().keys())
      test(`mode ${mode}: write #${index}`, async () => {
        const command = writes()[index]!
        const verdict = verdictOf(await shellInput(command, mode, [note, path.join(mirror, "x/notes/b.md")]))
        expect([command, verdict.class, verdict.category]).toEqual([command, "X", "vault_mirror"])
      })

  const reads = () => [
    `cat ${mirror}/x/notes/a.md`,
    `ls ${mirror}/x`,
    `head -n 3 ${mirror}/x/notes/a.md`,
    `grep -r synthetic ${mirror}`,
    `cp ${mirror}/x/notes/a.md copy.md`,
  ]
  for (const index of reads().keys())
    test(`reads stay allowed (mode consent): read #${index}`, async () => {
      const command = reads()[index]!
      const verdict = verdictOf(await shellInput(command, "consent"))
      expect([command, verdict.category === "vault_mirror"]).toEqual([command, false])
    })

  test("a shell write into <vault>/inbox is not vault_mirror", async () => {
    for (const mode of ["on", "consent"] as const) {
      const verdict = verdictOf(await shellInput(`echo synthetic > ${vault}/inbox/n.md`, mode, [path.join(vault, "inbox/n.md")]))
      expect(verdict.category).not.toBe("vault_mirror")
    }
  })
})

describe("SEC11 the edit tools: refused without asking (mode off), with an \"always\" edit rule present", () => {
  afterEach(async () => {
    await disposeAllInstances()
  })
  const it = testEffect(
    LayerNode.compile(
      LayerNode.group([LSP.node, FSUtil.node, EventV2Bridge.node, Format.node, CrossSpawnSpawner.node, Truncate.node, Agent.node]),
    ),
  )
  // The ask answers yes to everything, as a person's "always" for edits and outside folders would.
  const context = (asked: string[]) => ({
    sessionID: SessionID.make("ses_test-sec11"),
    messageID: MessageID.make("msg_test"),
    callID: "",
    agent: "build",
    abort: AbortSignal.any([]),
    messages: [],
    metadata: () => Effect.void,
    trust: { canUndo: true },
    ask: (input: { permission: string }) => Effect.sync(() => void asked.push(input.permission)),
  })

  it.instance("write, edit and apply_patch into swarm-memory: refused with N8-442, nothing asked, nothing written", () =>
    Effect.gen(function* () {
      const asked: string[] = []
      const ctx = context(asked) as never
      const write = yield* (yield* WriteTool).init()
      const edit = yield* (yield* EditTool).init()
      const patch = yield* (yield* ApplyPatchTool).init()
      const results = [
        yield* write.execute({ filePath: note, content: "new\n" }, ctx).pipe(Effect.exit),
        yield* write.execute({ filePath: path.join(mirror, "x/notes/extra.md"), content: "new\n" }, ctx).pipe(Effect.exit),
        yield* edit.execute({ filePath: note, oldString: "synthetic", newString: "new" }, ctx).pipe(Effect.exit),
        yield* patch
          .execute({ patchText: `*** Begin Patch\n*** Add File: ${path.join(mirror, "x/notes/added.md")}\n+new\n*** End Patch` }, ctx)
          .pipe(Effect.exit),
      ]
      for (const exit of results) expect(failure(exit)).toContain(N8_442)
      expect(asked).toEqual([])
      expect(readFileSync(note, "utf8")).toBe("synthetic mirror note\n")
      expect(existsSync(path.join(mirror, "x/notes/extra.md"))).toBe(false)
      expect(existsSync(path.join(mirror, "x/notes/added.md"))).toBe(false)
    }),
  )

  it.instance("a write into <vault>/inbox still gets its outside-folder prompt (unchanged)", () =>
    Effect.gen(function* () {
      const asked: string[] = []
      const write = yield* (yield* WriteTool).init()
      const exit = yield* write
        .execute({ filePath: path.join(vault, "inbox/n.md"), content: "new\n" }, context(asked) as never)
        .pipe(Effect.exit)
      expect(failure(exit)).not.toContain(N8_442)
      expect(asked[0]).toBe("external_directory")
    }),
  )
})

