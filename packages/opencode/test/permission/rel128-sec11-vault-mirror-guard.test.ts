function seedVault(root: string) {
  for (const sub of ["swarm-memory/x/notes", "inbox", "notes", "swarm-memory-old"]) mkdirSync(path.join(root, sub), { recursive: true })
  writeFileSync(path.join(root, "swarm-memory/x/notes/a.md"), "synthetic mirror note\n")
  writeFileSync(path.join(root, "notes/own.md"), "synthetic own note\n")
}

