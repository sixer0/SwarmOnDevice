import { Memory } from "@/memory/memory"
import { Schema } from "effect"
import { HttpApi, HttpApiEndpoint, HttpApiError, HttpApiGroup, OpenApi } from "effect/unstable/httpapi"
import { Authorization } from "../middleware/authorization"
import { InstanceContextMiddleware } from "../middleware/instance-context"
import {
  WorkspaceRoutingMiddleware,
  WorkspaceRoutingQuery,
  WorkspaceRoutingQueryFields,
} from "../middleware/workspace-routing"
import { DesktopNonceHeaders } from "./autonomy"
import { described } from "./metadata"

const root = "/memory"

// 1.2.10 row 54a (N10-001, N10-002; C18, C31): where a note may go is the person's call. `POST /memory/:id/vault` and a
// `PATCH /memory/:id` that carries `deviceOnly` are taken only with the per-launch desktop nonce (strict: a server
// holding no nonce, as `swarm serve`, refuses everyone). The password is readable by an agent's shell; the nonce is not.
export const MEMORY_PERSON_ONLY = "MEMORY_PERSON_ONLY"
export const MEMORY_PERSON_ONLY_MESSAGE = "Only the person in the Swarm desktop app can change where a note may go."

export class ApiMemoryPersonOnlyError extends Schema.ErrorClass<ApiMemoryPersonOnlyError>("MemoryPersonOnlyError")(
  {
    name: Schema.Literal("MemoryPersonOnlyError"),
    data: Schema.Struct({
      code: Schema.Literal(MEMORY_PERSON_ONLY),
      message: Schema.String,
    }),
  },
  { httpApiStatus: 403 },
) {}

// 1.2.10 row 54a (N10-066, C18 D-7): why a note stays out of the vault copy, computed by `mirrorExclusion` (plus
// "unsafe" for an id the mirror cannot use as a file name). Ids and reasons only, never the note text.
export const MemoryKeptReason = Schema.Literals(["device", "secret", "classified", "unsafe"]).annotate({
  identifier: "MemoryKeptReason",
})

// GET /memory/vault (N8-114, 01c §6, AC-OBSe): the vault mirror of this project's memory.
const VaultQuery = Schema.Struct({
  ...WorkspaceRoutingQueryFields,
  language: Schema.optional(Schema.Literals(["en", "id"])).annotate({
    description: "The app's language for the generated note labels; remembered for the next mirror run",
  }),
})

const VaultStatus = Schema.Struct({
  folder: Schema.String.annotate({ description: "The project's folder name under <vault>/swarm-memory/" }),
  hubPath: Schema.String.annotate({ description: "Absolute path of the project's index note in the vault" }),
  exists: Schema.Boolean.annotate({
    description: "The index note is present, a regular file, and still generated by Swarm for this project",
  }),
  kept: Schema.optional(
    Schema.Array(Schema.Struct({ id: Schema.String, reason: MemoryKeptReason })).annotate({
      description: "The live notes that stay out of the vault copy, each with its reason. Ids and reasons only",
    }),
  ),
})

export const MemoryApi = HttpApi.make("memory")
  .add(
    HttpApiGroup.make("memory")
      .add(
        HttpApiEndpoint.get("get", root, {
          query: WorkspaceRoutingQuery,
          success: described(Memory.Info, "What this project's sessions start out knowing"),
        }).annotateMerge(
          OpenApi.annotations({
            identifier: "memory.get",
            summary: "Get project memory",
            description: "List the notes every new session on this project starts with.",
          }),
        ),
        HttpApiEndpoint.get("vault", `${root}/vault`, {
          query: VaultQuery,
          success: described(VaultStatus, "Where this project's notes are mirrored in the Swarm vault"),
          error: HttpApiError.BadRequest,
        }).annotateMerge(
          OpenApi.annotations({
            identifier: "memory.vault",
            summary: "Get the vault mirror of project memory",
            description:
              "Return the project's folder under the vault's swarm-memory folder, the path of its index note, and whether that note exists and is still Swarm's own. Writes nothing. A language, when given, is remembered for the next mirror run, which then re-renders the generated labels once in that language.",
          }),
        ),
        HttpApiEndpoint.post("add", root, {
          query: WorkspaceRoutingQuery,
          payload: Schema.Struct({ text: Schema.String }),
          success: described(Memory.Result, "The stored note, or why it was refused"),
          error: HttpApiError.BadRequest,
        }).annotateMerge(
          OpenApi.annotations({
            identifier: "memory.add",
            summary: "Add a note",
            description: "Add a note written by the user. Text that looks like a credential is refused.",
          }),
        ),
        HttpApiEndpoint.patch("settings", root, {
          query: WorkspaceRoutingQuery,
          payload: Schema.Struct({ enabled: Schema.Boolean }),
          success: described(Memory.Info, "The updated memory"),
          error: HttpApiError.BadRequest,
        }).annotateMerge(
          OpenApi.annotations({
            identifier: "memory.settings",
            summary: "Turn project memory on or off",
            description: "When off, sessions receive no notes and nothing new is learned. Notes are kept.",
          }),
        ),
        HttpApiEndpoint.patch("update", `${root}/:id`, {
          params: { id: Schema.String },
          query: WorkspaceRoutingQuery,
          headers: DesktopNonceHeaders,
          payload: Schema.Struct({
            text: Schema.optional(Schema.String),
            deviceOnly: Schema.optional(Schema.Boolean),
          }),
          success: described(Memory.Result, "The updated note, or why the change was refused"),
          error: [ApiMemoryPersonOnlyError, HttpApiError.BadRequest],
        }).annotateMerge(
          OpenApi.annotations({
            identifier: "memory.update",
            summary: "Change a note",
            description: "Rewrite a note, or set whether it may leave this device.",
          }),
        ),
        HttpApiEndpoint.post("allowVault", `${root}/:id/vault`, {
          params: { id: Schema.String },
          query: WorkspaceRoutingQuery,
          headers: DesktopNonceHeaders,
          payload: Schema.Struct({ allowed: Schema.Boolean }),
          success: described(Memory.Result, "The note, or why it may not be copied"),
          error: [ApiMemoryPersonOnlyError, HttpApiError.BadRequest],
        }).annotateMerge(
          OpenApi.annotations({
            identifier: "memory.allowVault",
            summary: "Allow or stop a note in the vault",
            description:
              "Person only (Swarm desktop app): allow a device-only note into the Obsidian vault copy, or remove it. Never changes which models may receive the note.",
          }),
        ),
        HttpApiEndpoint.delete("remove", `${root}/:id`, {
          params: { id: Schema.String },
          query: WorkspaceRoutingQuery,
          success: described(Schema.Boolean, "Whether a note was removed"),
        }).annotateMerge(
          OpenApi.annotations({
            identifier: "memory.remove",
            summary: "Remove a note",
            description: "Remove a note from the project memory.",
          }),
        ),
      )
      .annotateMerge(OpenApi.annotations({ title: "memory", description: "Project memory routes." }))
      .middleware(InstanceContextMiddleware)
      .middleware(WorkspaceRoutingMiddleware)
      .middleware(Authorization),
  )
  .annotateMerge(
    OpenApi.annotations({
      title: "swarm HttpApi",
      version: "0.0.1",
      description: "Effect HttpApi surface for instance routes.",
    }),
  )
