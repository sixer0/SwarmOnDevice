// Swarm 1.3.3 row 37 (ST-1 item 5, C13): the published capacity resource equals the data file of row 36, and the guide
// stays within its pin. Refresh the stored text: ROW37_WRITE=1 bun test test/st1-capacity-table/row37-capacity-resource.test.ts
import { describe, expect, test } from "bun:test"
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { CAPACITY_WORDING, DIAGRAM_CAPACITY_NAME, DIAGRAM_CAPACITY_URI, capacityGuideText, renderCapacityTable, type CapacityData } from "../../src/mcp-host/capacity-guide.ts"
import { diagramGuideText, DIAGRAM_GUIDE_EXAMPLE } from "../../src/mcp-host/diagram-guide.ts"

const DATA = path.join(import.meta.dir, "capacity-table.json")
const TEXT = path.join(import.meta.dir, "..", "..", "src", "mcp-host", "capacity-guide.text.ts")
const data = JSON.parse(readFileSync(DATA, "utf8")) as CapacityData
const fresh = renderCapacityTable(data)

if (process.env.ROW37_WRITE === "1")
  writeFileSync(TEXT, `// Generated by test/st1-capacity-table/row37-capacity-resource.test.ts (ROW37_WRITE=1). Do not edit by hand.\nexport const CAPACITY_TABLE_TEXT = ${JSON.stringify(fresh)}\n`)

describe("row 37: capacity resource", () => {
  test("uri and name", () => {
    expect(DIAGRAM_CAPACITY_URI).toBe("studio://kapasitas/diagram")
    expect(DIAGRAM_CAPACITY_NAME).toBe("kapasitas-diagram")
  })

  test("the published text equals the table rendered from the data file", async () => {
    const mod = await import(`../../src/mcp-host/capacity-guide.text.ts?v=${Date.now()}`)
    expect(mod.CAPACITY_TABLE_TEXT).toBe(fresh)
    expect(capacityGuideText().length).toBeGreaterThan(500)
  })

  test("every data row has English wording and a limit per width; every limit appears in its row", () => {
    const rows = data.capacity.rows
    expect(Object.keys(CAPACITY_WORDING).sort()).toEqual(rows.map((r) => r.key).sort())
    const lines = fresh.split("\n").filter((l) => l.startsWith("| ") && !l.startsWith("| Family"))
    expect(lines.length).toBe(rows.length)
    rows.forEach((r, i) => {
      const cells = lines[i].split(" | ")
      const t = r.cells.find((c) => c.width === "text")!
      const f = r.cells.find((c) => c.width === "full")!
      expect(cells[3]).toBe(t.capped ? `${t.limit} or more` : String(t.limit))
      expect(cells[4]).toBe(f.capped ? `${f.limit} or more` : String(f.limit))
    })
  })

  test("headline cells (row 36 data after rows 138-142)", () => {
    expect(fresh).toContain("| layered | nodes per tier | 2 tiers | 3 | 4 | DATUM-37-sheet |")
    expect(fresh).toContain("| rack | devices of 1U | 1 rack, one connector | 23 | 23 | DATUM-33 + split skeleton |")
    expect(fresh).toContain("Labelled tiers")
    expect(fresh).not.toMatch(/\bPDS|pustaka|\bKL\b/)
  })

  test("the resource list description of the diagram guide names the capacity resource", () => {
    const src = readFileSync(path.join(import.meta.dir, "..", "..", "src", "mcp-host", "mcp-server.ts"), "utf8")
    expect(src).toContain("DIAGRAM_CAPACITY_URI + \".\"")
    expect(src).toContain("uri: DIAGRAM_CAPACITY_URI")
  })

  test("guide: no labels_verified, within the 3000 B pin", () => {
    const t = diagramGuideText()
    console.log(`[row37] guide ${Buffer.byteLength(t)} B`)
    expect(Buffer.byteLength(t)).toBeLessThan(3000)
    // The pointer does not fit the 3000 B pin: it is in the resource list description (mcp-server.ts, checked in the host test).
    expect(t.split("```json")[1]).not.toContain("labels_verified") // the schema field stays in the field list; the example no longer sends it
    expect(JSON.stringify(DIAGRAM_GUIDE_EXAMPLE)).not.toContain("labels_verified")
    expect(t).not.toContain("~20 characters")
    expect(t).toContain("Edge kinds max 6, by pattern; DATUM-25 counts fill and accent colours only (DATUM-25L).")
  })
})
